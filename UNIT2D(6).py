name = "Meghana"
age = 18
marks = 95.5

# Using format()
print("Using format(): Name is {}, Age is {}, Marks are {}".format(name, age, marks))

# Using f-strings
print(f"Using f-string: Name is {name}, Age is {age}, Marks are {marks}")

# Using % operator
print("Using %% operator: Name is %s, Age is %d, Marks are %.1f" % (name, age, marks))